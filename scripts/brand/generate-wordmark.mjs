#!/usr/bin/env node
// 코드젠 — "서포트 B" 워드마크를 커스텀 SVG 벡터 패스로 생성한다.
//
// 왜: 시스템 폰트 텍스트("font-black" span)는 폰트 로딩·플랫폼별 렌더링에 따라 흔들리고
// 브랜드 개성이 없다. 이 스크립트는 self-host 중인 Pretendard(SIL OFL)의 글리프 아웃라인을
// 직접 추출해 "서포트" 3글자 + 브랜드 마크(같은 BRAND_MARK_PATH, `lib/brand/brand-mark-path.ts`
// SSOT)를 "B" 자리에 합성한 단일 벡터 락업을 만든다. 마크와 워드마크 끝 글자가 같은 형태를
// 공유해 어디서나 픽셀 단위로 동일하게 보이고(통일성) 반복 노출로 기억에 남는다(mark-as-letter).
//
// fontkit은 이 프로젝트가 쓰는 Variable 폰트(PretendardVariable.woff2)의 gvar 콤포짓 글리프
// 보간에서 크래시하는 알려진 버그가 있어(foliojs/fontkit 계열, composite glyph phantom points),
// 정적 Black weight OTF(devDependency `pretendard` 패키지, 같은 폰트 패밀리)에서 추출한다 —
// 런타임에는 전혀 관여하지 않고 이 코드젠 스크립트에서만 쓰는 빌드타임 전용 자산이다.
//
// 실행: `pnpm brand:wordmark` — 출력은 `components/primitives/wordmark-paths.generated.ts`.
// 좌표계: fontkit 글리프 패스는 폰트 표준(y-up, baseline=0, 오름선이 +y) 좌표이므로 각 글리프에
// scale(1,-1)을 적용해 SVG 네이티브(y-down) 좌표로 뒤집고, 그다음 누적 advance만큼 x축으로
// 옮겨 한 줄로 이어붙인다. 마크는 이미 자기 그룹 트랜스폼(`translate(0 1254) scale(0.1 -0.1)`)
// 자체가 SVG 네이티브 좌표를 만들어내므로(BrandMark 컴포넌트가 그대로 그려온 값 그대로) 뒤집지
// 않고, 그 결과를 라틴 "B"의 실측 cap-height에 맞춰 스케일 후 마지막 글리프 자리에 붙인다.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { openSync } from 'fontkit';
import svgpath from 'svgpath';

const ROOT = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '../..');

const BRAND_MARK_SOURCE_PATH = path.join(ROOT, 'lib/brand/brand-mark-path.ts');
const FONT_PATH = path.join(
  ROOT,
  'node_modules/pretendard/dist/public/static/Pretendard-Black.otf',
);
const OUTPUT_PATH = path.join(ROOT, 'components/primitives/wordmark-paths.generated.ts');

const HANGUL_TEXT = '서포트';
// 실제 공백 글리프의 advance — "서포트"와 마크(B 자리) 사이 간격을 인위적인 매직 넘버 대신
// 이 폰트가 정의한 실측 공백 폭으로 둬 자연스러운 워드 스페이싱을 재현한다.
const SPACE_CODEPOINT = 0x20;

function extractBrandMarkPath(source) {
  const match = source.match(/BRAND_MARK_PATH =\s*\n\s*'([^']+)'/);
  if (!match) {
    throw new Error('BRAND_MARK_PATH를 lib/brand/brand-mark-path.ts에서 찾지 못했습니다 — SSOT 정규식이 깨졌는지 확인하세요.');
  }
  return match[1];
}

function buildHangulGlyphPaths(font) {
  const glyphs = font.glyphsForString(HANGUL_TEXT);
  let x = 0;
  const paths = [];
  for (const glyph of glyphs) {
    const d = svgpath(glyph.path.toSVG()).scale(1, -1).translate(x, 0).toString();
    paths.push(d);
    x += glyph.advanceWidth;
  }
  return { paths, endX: x };
}

/**
 * BRAND_MARK_PATH(원본 potrace 트레이스, 1254px 캔버스 기준)를 BrandMark 컴포넌트가 쓰는
 * 그룹 트랜스폼 `translate(0 1254) scale(0.1 -0.1)`과 동일하게 적용해 "네이티브" 좌표로
 * 정규화한다 — bbox는 `334 294 636 636`(BrandMark의 viewBox와 동일, 정사각형).
 */
function normalizeBrandMarkPath(rawPath) {
  const NATIVE_BBOX = { minX: 334, minY: 294, size: 636 };
  const nativeD = svgpath(rawPath).scale(0.1, -0.1).translate(0, 1254).toString();
  return { nativeD, bbox: NATIVE_BBOX };
}

function buildMarkGlyphPath(rawPath, targetCapHeight, xOffset) {
  const { nativeD, bbox } = normalizeBrandMarkPath(rawPath);
  const scale = targetCapHeight / bbox.size;
  const d = svgpath(nativeD)
    .translate(-bbox.minX, -(bbox.minY + bbox.size))
    .scale(scale, scale)
    .translate(xOffset, 0)
    .round(2)
    .toString();
  return { d, width: bbox.size * scale };
}

function main() {
  const brandMarkSource = readFileSync(BRAND_MARK_SOURCE_PATH, 'utf8');
  const rawMarkPath = extractBrandMarkPath(brandMarkSource);

  const font = openSync(FONT_PATH);
  const { unitsPerEm, ascent, descent } = font;

  const { paths: hangulPaths, endX: hangulEndX } = buildHangulGlyphPaths(font);
  const gap = font.glyphForCodePoint(SPACE_CODEPOINT).advanceWidth;
  const markStartX = hangulEndX + gap;

  // 라틴 "B"의 실측 cap-height에 맞춰 마크 크기를 정한다 — 마크가 대신하는 글자의 자연스러운
  // 크기를 그대로 물려받아 임의 스케일값 없이 근거 있는 비율이 된다.
  const latinB = font.glyphForCodePoint(0x42);
  const capHeight = latinB.bbox.maxY;

  const { d: markD, width: markWidth } = buildMarkGlyphPath(rawMarkPath, capHeight, markStartX);

  const glyphs = [...hangulPaths, markD];
  const totalWidth = markStartX + markWidth;

  const output = `// AUTO-GENERATED by \`pnpm brand:wordmark\` (scripts/brand/generate-wordmark.mjs) — 직접 수정 금지.
// "서포트 B" 워드마크 벡터 패스. 좌표계는 Pretendard 폰트 단위(baseline y=0, 오름선 -y)이며
// SVG에 그대로 꽂아 쓸 수 있도록 이미 y-down으로 뒤집혀 있다. glyphs 마지막 원소가 브랜드
// 마크(B 자리) — lib/brand/brand-mark-path.ts의 BrandMark와 같은 형태를 공유한다.

export const WORDMARK_PATHS = {
  unitsPerEm: ${unitsPerEm},
  ascent: ${ascent},
  descent: ${descent},
  totalWidth: ${totalWidth},
  glyphs: [
${glyphs.map((d) => `    '${d}',`).join('\n')}
  ],
} as const
`;

  writeFileSync(OUTPUT_PATH, output);
  console.log(`워드마크 패스 생성 완료 → ${path.relative(ROOT, OUTPUT_PATH)}`);
  console.log(`  glyphs: ${glyphs.length}, totalWidth: ${totalWidth}, unitsPerEm: ${unitsPerEm}`);
}

main();
