import { render, screen } from '@testing-library/react';
import { describe, it, expect } from 'vitest';
import { BidPdfPane } from '../BidPdfPane';

describe('BidPdfPane', () => {
  it('PDF 가 없으면 큰 미리보기 높이를 잡지 않고 한 줄 안내만 보여준다', () => {
    const { container } = render(<BidPdfPane />);
    expect(screen.getByText('견적서 미첨부')).toBeInTheDocument();
    // 이미 제출된 견적에만 보이므로 PDF가 나중에 올 것처럼 말하지 않는다.
    expect(screen.getByText('PG사가 PDF를 첨부하지 않았어요.')).toBeInTheDocument();
    // 장식 아이콘은 스크린리더가 읽지 않는다.
    expect(container.querySelector('svg')).toHaveAttribute('aria-hidden', 'true');
    expect(container.innerHTML).not.toMatch(/min-h-\[/);
  });

  // Generated by /ship coverage audit.
  // Value: protects=placeholder attachments (sentinel name or empty url) render the compact notice, not an iframe;
  //   fails_when=the hasPdf guard drops the sentinel-name or url check;
  //   why_new=the case above covers only pdf=undefined; seam=none;
  //   no_claim=which upstream producers emit the sentinel (jsdom render only)
  it.each([
    ['자리표시 이름', { id: 'p', name: '견적서 미첨부', url: '/api/files/p' }],
    ['빈 url', { id: 'e', name: 'proposal.pdf', url: '' }],
  ])('%s 첨부도 미리보기 대신 한 줄 안내를 보여준다', (_label, pdf) => {
    const { container } = render(<BidPdfPane pdf={pdf as never} />);
    expect(screen.getByText('견적서 미첨부')).toBeInTheDocument();
    expect(container.querySelector('iframe')).toBeNull();
    expect(container.innerHTML).not.toMatch(/min-h-\[/);
  });

  it('PDF 가 있으면 미리보기 높이를 확보한다', () => {
    const { container } = render(
      <BidPdfPane pdf={{ id: 'a', name: 'proposal.pdf', url: '/api/files/a' } as never} />,
    );
    expect(screen.getByTitle('proposal.pdf')).toBeInTheDocument();
    expect(container.innerHTML).toMatch(/min-h-\[400px\]/);
  });
});
