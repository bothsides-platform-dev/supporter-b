/**
 * 새 조항형 서식의 시드 문서.
 *
 * **호출마다 새 객체를 만든다** — 모듈 상수를 그대로 돌려주면 편집기가 그 자리에서
 * 고친 값이 다음에 만드는 서식에 그대로 새어 들어간다.
 */
