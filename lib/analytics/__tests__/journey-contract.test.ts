import { expect, it } from "vitest";
import {
  journeyInputSchema,
  sanitizeJourneyEvent,
  formatJourneyEvents,
  formatJourneyAnalytics,
} from "@/lib/guest-rfp/journey-contract";
const event = {
  id: "10000000-0000-4000-8000-000000000001",
  name: "funnel_step_error",
  funnel_id: "questions",
  step_id: "industry",
  observedAt: "2026-10-20T05:03:45.000Z",
  error_code: "VALIDATION",
};
it("allows only defined steps and fixed errors, never input text or browser success claims", () => {
  const input = { draftId: event.id, op: "events", events: [event] };
  expect(journeyInputSchema.safeParse(input).success).toBe(true);
  for (const change of [
    { memo: "secret" },
    { step_id: "secret" },
    { error_code: "email@example.com" },
    { name: "sign_up" },
    { name: "quote_request_submitted" },
  ])
    expect(
      journeyInputSchema.safeParse({
        ...input,
        events: [{ ...event, ...change }],
      }).success,
    ).toBe(false);
  expect(
    sanitizeJourneyEvent("funnel_step_error", {
      funnel_id: "questions",
      step_id: "industry",
      error_code: "raw secret",
    }),
  ).toMatchObject({ error_code: "UNKNOWN" });
  expect(
    sanitizeJourneyEvent("sign_up", {
      funnel_id: "signup",
      step_id: "account_created",
    }),
  ).toBeNull();
});
it("keeps repeated errors and chronological KST timestamps without answer contents", () => {
  const later = {
    ...event,
    id: "20000000-0000-4000-8000-000000000001",
    observedAt: "2026-10-20T05:03:58.000Z",
  };
  const text = formatJourneyEvents([later, event] as never);
  expect(text).toContain("14:03:45 업종 입력 오류");
  expect(text).toContain("14:03:58 업종 입력 오류");
  expect(text.indexOf("14:03:45")).toBeLessThan(text.indexOf("14:03:58"));
});
it("distinguishes a replay link from verified playback and never constructs a GA user URL", () => {
  const text = formatJourneyAnalytics(
    [
      {
        observedAt: event.observedAt,
        clarity: { userId: "u1", sessionId: "s1" },
        ga: { clientId: "123.456", sessionId: "123" },
      },
    ],
    "user-id",
    "https://analytics.google.com/analytics/web/#/analysis/p540469131/edit/report",
  );
  expect(text).toContain(
    "https://clarity.microsoft.com/player/xiq81e87yn/u1/s1",
  );
  expect(text).toContain("재생 가능 여부는 확인하지 않았어요");
  expect(text).toContain("123.456");
  expect(text).toContain("user-id");
  expect(formatJourneyAnalytics([], null, undefined)).toContain(
    "식별자 미확보",
  );
});

it("uses the Korean calendar date at the UTC day boundary", () => {
  expect(
    formatJourneyAnalytics([{ observedAt: "2026-10-20T16:00:00.000Z" }], null),
  ).toContain("2026-10-21");
});

it("accepts bounded question answers and escapes Slack control markup", () => {
  const completed = { ...event, name: "funnel_step_complete", answer: "< !channel > & test" };
  const parsed = journeyInputSchema.safeParse({ draftId: event.id, op: "events", events: [completed] });
  expect(parsed.success).toBe(true);
  expect(formatJourneyEvents([completed] as never)).toContain("업종 입력 완료: &lt; !channel &gt; &amp; test");
  for (const change of [{ name: "funnel_step_view" }, { funnel_id: "signup", step_id: "email_verification" }, { answer: "a".repeat(501) }]) {
    expect(journeyInputSchema.safeParse({ draftId: event.id, op: "events", events: [{ ...completed, ...change }] }).success).toBe(false);
  }
});

it.each(['email', 'company', 'profile', 'phone'])('preserves an approved signup answer for %s only', (step) => {
 const parsed = sanitizeJourneyEvent('funnel_step_complete', {funnel_id:'signup', step_id:step, journey_answer:'입력값'});
 expect(parsed).toMatchObject({answer:'입력값'});
 expect(journeyInputSchema.safeParse({draftId:event.id, op:'events', events:[parsed]}).success).toBe(true);
});

// Generated by /ship coverage audit.
// Value: protects=answer truncation and exclusion on non-completion or skipped steps;
// fails_when=raw answers bypass the 500-character cap or enter skip/error/view events;
// why_new=existing assertions cover server rejection but not the client sanitizer boundary;
// seam=none; no_claim=Slack provider acceptance (pure contract test).
it("caps answer snapshots and omits them from skipped, viewed, errored or unapproved steps", () => {
  const input = { funnel_id: 'questions' as const, step_id: 'memo', journey_answer: '한'.repeat(501) };
  const completed = sanitizeJourneyEvent('funnel_step_complete', input);
  expect(completed?.answer).toBe('한'.repeat(499) + '…');
  expect(sanitizeJourneyEvent('funnel_step_complete', { ...input, journey_answer: '한'.repeat(500) })?.answer).toBe('한'.repeat(500));
  for (const sanitized of [
    sanitizeJourneyEvent('funnel_step_complete', { ...input, progression: 'skip' }),
    sanitizeJourneyEvent('funnel_step_view', input),
    sanitizeJourneyEvent('funnel_step_error', input),
    sanitizeJourneyEvent('funnel_step_complete', { ...input, funnel_id: 'signup', step_id: 'email_verification' }),
  ]) {
    expect(sanitized).not.toBeNull();
    expect(sanitized).not.toHaveProperty('answer');
  }
  const base = { ...event, name: 'funnel_step_complete', answer: 'first\r\nsecond' };
  expect(formatJourneyEvents([base] as never)).toContain('입력 완료: first / second');
  expect(formatJourneyEvents([{ ...base, answer: '' }] as never)).toContain('입력 완료: 미입력');
  expect(journeyInputSchema.safeParse({ draftId: event.id, op: 'events', events: [{ ...base, progression: 'skip' }] }).success).toBe(false);
});
